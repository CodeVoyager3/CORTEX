import { prisma } from '../../../package/db/prisma';
import { ragService } from './rag.service';
import { blastRadiusService, ImpactedChunk } from './blastRadius.service';
import { buildReviewPrompt, runReview, type ReviewIssue } from '../../../package/ai/review';

export type { ReviewIssue };

export interface ReviewResult {
  reviewId: string;
  status: 'completed' | 'failed';
  issues: ReviewIssue[];
  blastRadius: ImpactedChunk[];
  commentBody: string;
}

function extractChangedFilePaths(diffText: string): string[] {
  const matches = [...diffText.matchAll(/^diff --git a\/([^\s]+) b\/([^\s]+)$/gm)];
  const filePaths: string[] = matches
    .map((match) => (match[1] || match[2] || '').trim())
    .filter((filePath): filePath is string => Boolean(filePath) && !filePath.startsWith('"'));

  return [...new Set(filePaths)];
}

function extractChangedSymbolNames(diffText: string): string[] {
  const symbolPatterns = [
    /(?:export\s+)?(?:async\s+)?function\s+([A-Za-z0-9_]+)/g,
    /(?:export\s+)?(?:const|let|var)\s+([A-Za-z0-9_]+)\s*=/g,
    /(?:export\s+)?(?:class|interface|type)\s+([A-Za-z0-9_]+)/g,
    /\b([A-Za-z0-9_]+)\s*:\s*(?:string|number|boolean|unknown|any|Record<|Promise<|Array<)/g,
  ];

  const symbols = new Set<string>();

  for (const pattern of symbolPatterns) {
    let match: RegExpExecArray | null;
    while ((match = pattern.exec(diffText)) !== null) {
      const symbolName = match[1]?.trim();
      if (symbolName && !symbolName.startsWith('0')) {
        symbols.add(symbolName);
      }
    }
  }

  return [...symbols];
}

function formatCommentBody(issues: ReviewIssue[], blastRadius: ImpactedChunk[]): string {
  const severityOrder: Record<string, number> = {
    critical: 0,
    high: 1,
    medium: 2,
    low: 3,
  };

  const sortedIssues = [...issues].sort(
    (a, b) => (severityOrder[a.severity] ?? 9) - (severityOrder[b.severity] ?? 9),
  );

  const issueLines =
    sortedIssues.length > 0
      ? sortedIssues
          .map(
            (issue) =>
              `- **[${issue.severity}]** \`${issue.filePath}:${issue.lineNumber}\` — ${issue.description}`,
          )
          .join('\n')
      : '_No issues detected._';

  const blastLines =
    blastRadius.length > 0
      ? blastRadius
          .map(
            (impact) =>
              `- \`${impact.filePath}\` :: \`${impact.symbolName}\` (${impact.reason})`,
          )
          .join('\n')
      : '_No downstream dependents found in the index._';

  const uniqueFiles = new Set(blastRadius.map((b) => b.filePath)).size;

  return [
    '## CORTEX Review',
    '',
    '### Issues',
    issueLines,
    '',
    '### Blast Radius',
    blastRadius.length > 0
      ? `Changes may affect **${blastRadius.length}** symbol(s) across **${uniqueFiles}** file(s):`
      : 'No blast-radius impact detected from the current index.',
    blastLines,
    '',
    '---',
    '_Generated by CORTEX_',
  ].join('\n');
}

export class ReviewService {
  public async reviewPullRequest(
    repositoryId: string,
    prNumber: number,
    diffText: string,
  ): Promise<ReviewResult> {
    const review = await prisma.pRReview.create({
      data: { repositoryId, prNumber, status: 'pending' },
    });

    try {
      const changedFilePaths = extractChangedFilePaths(diffText);
      const changedSymbolNames = extractChangedSymbolNames(diffText);
      const blastRadius = await blastRadiusService.calculateBlastRadius(
        repositoryId,
        changedFilePaths,
        changedSymbolNames,
      );

      const blastRadiusSummary =
        blastRadius.length > 0
          ? blastRadius
              .map((impact) => `- ${impact.filePath} :: ${impact.symbolName} (${impact.reason})`)
              .join('\n')
          : 'No downstream dependents were detected in the repository index.';

      const contextSnippets = await ragService.retrieveContextForDiff(repositoryId, diffText);
      const repositoryContext = contextSnippets
        .map(
          (c) =>
            `File: ${c.filePath}\nCode:\n${c.content}\nImports: ${c.imports.join(', ')}\nCalls: ${c.calledBy.join(', ')}`,
        )
        .join('\n\n');

      const prompt = buildReviewPrompt({ diffText, blastRadiusSummary, repositoryContext });
      const issues = await runReview(prompt);

      if (issues.length > 0) {
        await prisma.issue.createMany({
          data: issues.map((issue) => ({
            reviewId: review.id,
            filePath: issue.filePath,
            lineNumber: issue.lineNumber,
            description: issue.description,
            severity: issue.severity,
          })),
        });
      }

      await prisma.pRReview.update({
        where: { id: review.id },
        data: { status: 'completed' },
      });

      const commentBody = formatCommentBody(issues, blastRadius);
      console.log(`[Review] PR #${prNumber} completed successfully.`);

      return {
        reviewId: review.id,
        status: 'completed',
        issues,
        blastRadius,
        commentBody,
      };
    } catch (error) {
      console.error(`[Review] Failed for PR #${prNumber}:`, error);
      await prisma.pRReview.update({
        where: { id: review.id },
        data: { status: 'failed' },
      });

      return {
        reviewId: review.id,
        status: 'failed',
        issues: [],
        blastRadius: [],
        commentBody: '',
      };
    }
  }
}

export const reviewService = new ReviewService();
